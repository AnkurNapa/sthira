"""Record every spoken sentence in the Emma voice (Kokoro bf_emma, British).

Run from the site folder:
    node tools/voice_lines.js > /tmp/lines.json
    ~/tts/kokoro-env/bin/python tools/voice_build.py /tmp/lines.json

Writes voice/<hash>.mp3 for each sentence plus voice/clips.js, the list voice.js
checks before playing. Sentences already recorded are skipped, so a rerun only fills gaps.
The hash must match clipKey() in voice.js.
"""
import json
import os
import re
import subprocess
import sys

import numpy as np
import soundfile as sf
from kokoro import KPipeline

VOICE = "bf_emma"
SPEED = 0.92  # a touch slower than normal for a calm class pace
OUT = "voice"


def norm(sentence: str) -> str:
    s = re.sub(r"\s+", " ", sentence.strip().lower())
    return re.sub(r"[.!?]+$", "", s)


def fnv1a(text: str) -> str:
    h = 0x811C9DC5
    for ch in text:
        h ^= ord(ch)
        h = (h * 0x01000193) & 0xFFFFFFFF
    return f"{h:08x}"


def main(lines_path: str) -> None:
    sentences = json.load(open(lines_path))
    os.makedirs(OUT, exist_ok=True)
    keys = {}
    for s in sentences:
        keys.setdefault(fnv1a(norm(s)), s)
    todo = [(k, s) for k, s in keys.items() if not os.path.exists(f"{OUT}/{k}.mp3")]
    print(f"{len(keys)} sentences, {len(todo)} to record", flush=True)
    if todo:
        pipe = KPipeline(lang_code="b")
        for n, (k, s) in enumerate(todo, 1):
            text = s if re.search(r"[.!?]$", s) else s + "."
            audio = np.concatenate([a for _, _, a in pipe(text, voice=VOICE, speed=SPEED)])
            wav = f"{OUT}/{k}.wav"
            sf.write(wav, audio, 24000)
            subprocess.run(
                ["ffmpeg", "-loglevel", "error", "-y", "-i", wav, "-ac", "1", "-b:a", "40k", f"{OUT}/{k}.mp3"],
                check=True,
            )
            os.remove(wav)
            if n % 50 == 0:
                print(f"recorded {n}", flush=True)
    with open(f"{OUT}/clips.js", "w") as f:
        f.write("// Generated by tools/voice_build.py. Sentences recorded in the Emma voice.\n")
        f.write("const EMMA_CLIPS = new Set(" + json.dumps(sorted(keys)) + ");\n")
    print("done", flush=True)


if __name__ == "__main__":
    main(sys.argv[1])
